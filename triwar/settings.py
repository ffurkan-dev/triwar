# Supabase Postgres via the transaction pooler (serverless friendly).
# Without DATABASE_URL we fall back to a local SQLite file for quick dev.
# MIGRATION_DATABASE_URL (session pooler / direct) is used by `manage.py migrate`.
_db_url = os.environ.get("DATABASE_URL")
if os.environ.get("USE_MIGRATION_DB") == "1" and os.environ.get("MIGRATION_DATABASE_URL"):
    _db_url = os.environ["MIGRATION_DATABASE_URL"]

if _db_url:
    DATABASES = {"default": dj_database_url.parse(_db_url, conn_max_age=0)}
    DATABASES["default"]["DISABLE_SERVER_SIDE_CURSORS"] = True
else:
    DATABASES = {"default": {"ENGINE": "django.db.backends.sqlite3", "NAME": BASE_DIR / "db.sqlite3"}}

